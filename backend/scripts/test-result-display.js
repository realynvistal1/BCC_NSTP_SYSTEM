'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').resolve(__dirname,'../../frontend/assets/common.js'),'utf8');
const context=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function responseProgress('),source.indexOf('function termFilters(')),context);
const legacy=context.ratingSummary({assignment:{response_count:2,average_rating:'3.00'}});
assert.ok(legacy.includes('Current average'));
assert.ok(legacy.includes('3.00 / 5'));
assert.ok(!legacy.includes('breakdown is currently unavailable'));
assert.ok(!legacy.includes('NaN'));
const partial=context.ratingSummary({assignment:{response_count:2,required_students:40,average_rating:3}});
assert.ok(partial.includes('38 more responses needed'));
assert.ok(!partial.includes('Final rating'));
const final=context.ratingSummary({assignment:{response_count:40,required_students:40,average_rating:4},summary:{required:40,final:true,positive:30,neutral:8,negative:2}});
assert.ok(final.includes('Final rating'));
assert.ok(final.includes('<strong>30</strong>'));
assert.ok(!final.includes('unavailable'));
assert.doesNotThrow(()=>context.ratingSummary());
assert.ok(!context.ratingSummary().includes('NaN'));
console.log('PASS: legacy responses, missing summary, missing target, partial results, and final results render safely.');
