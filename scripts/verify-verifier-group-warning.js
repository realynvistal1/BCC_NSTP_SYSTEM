const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={document:{addEventListener(){}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('public/js/shared/rotc-verifiers.js','utf8'),context);
const assignment={active:1,ms_level:'1',school_year:'2027-2028',mi_number:1,mi_type:'in',battalion:1,company:'Alpha',platoon:1,special_unit:''};
const selection={cycle:{ms_level:'1',school_year:'2027-2028'},miNumber:'1',miType:'in',battalion:'1',company:'Alpha',platoon:'1',special:false};
const matches=(a=assignment,s=selection)=>context.verifierGroupMatchesSelection(a,s);
assert(matches());
for(const cycle of [{ms_level:'2',school_year:'2027-2028'},{ms_level:'1',school_year:'2026-2027'}])assert(!matches(assignment,{...selection,cycle}));
for(const change of [{miNumber:'2'},{miType:'out'},{miNumber:''},{miType:''},{company:'Bravo'},{platoon:'2'},{battalion:'2'}])assert(!matches(assignment,{...selection,...change}));
assert(!matches({...assignment,active:0}));
assert(matches({...assignment,mi_number:0,mi_type:''}));
assert(!matches({...assignment,mi_number:0,mi_type:''},{...selection,miNumber:''}));
assert(matches({...assignment,special_unit:'Medics'},{...selection,special:true,specialUnit:'Medics'}));
assert(!matches({...assignment,special_unit:'HQ'},{...selection,special:true,specialUnit:'Medics'}));
assert.match(context.verifierScope(assignment),/MS 1 \/ SY 2027-2028 \/ MI 1 \/ IN/);
console.log('PASS: group warnings require the matching cycle, MI, type, and group; revoked and incomplete selections do not conflict; legacy all-MI assignments remain supported.');
